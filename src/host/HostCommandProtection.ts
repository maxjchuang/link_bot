import { accessSync, chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import { delimiter, resolve } from 'node:path';

export function installHostCommandProtection(projectRoot: string, env: NodeJS.ProcessEnv = process.env): string {
  const protectedBin = resolve(projectRoot, 'scripts/protected-bin');
  const wrapper = resolve(protectedBin, 'pm2');
  const realPm2 = findExecutable('pm2', env.PATH, protectedBin);
  if (!realPm2) throw new Error('Unable to locate the real PM2 executable before installing command protection.');
  chmodSync(wrapper, 0o755);
  env.LINK_BOT_REAL_PM2 = realPm2;
  env.PATH = `${protectedBin}${delimiter}${env.PATH ?? ''}`;
  return realPm2;
}

export function installHostCodexCommandPolicy(codexHome: string, realPm2: string): string {
  const rulesDirectory = resolve(codexHome, 'rules');
  const rulesPath = resolve(rulesDirectory, 'link-bot-host-manager.rules');
  mkdirSync(rulesDirectory, { recursive: true, mode: 0o700 });
  writeFileSync(rulesPath, renderHostManagerRules(realPm2), { mode: 0o600 });
  return rulesPath;
}

function renderHostManagerRules(realPm2: string): string {
  const justification = 'Use `npm run pm2:launch:linux` so the active turn card is finalized before host-manager restarts.';
  const lifecycleActions = '["restart", "reload", "stop", "delete", "kill"]';
  return [
    '# Generated by Link Bot. Direct host-manager lifecycle commands are unsafe.',
    'prefix_rule(',
    `    pattern = ["pm2", ${lifecycleActions}],`,
    '    decision = "forbidden",',
    `    justification = ${JSON.stringify(justification)},`,
    ')',
    '',
    'prefix_rule(',
    `    pattern = [${JSON.stringify(realPm2)}, ${lifecycleActions}],`,
    '    decision = "forbidden",',
    `    justification = ${JSON.stringify(justification)},`,
    ')',
    '',
  ].join('\n');
}

function findExecutable(name: string, path: string | undefined, excludedDirectory: string): string | undefined {
  for (const directory of (path ?? '').split(delimiter)) {
    if (!directory || resolve(directory) === resolve(excludedDirectory)) continue;
    const candidate = resolve(directory, name);
    try { accessSync(candidate); return candidate; } catch { /* continue */ }
  }
  return undefined;
}

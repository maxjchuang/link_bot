import type { SqliteStateStore } from '../state/SqliteStateStore.js';
import type { MemoryEntryRecord } from './MemoryTypes.js';

export interface MemoryProjectionSink {
  replace(taskId: string, files: ReadonlyMap<string, string>): Promise<void>;
}

export class MemoryProjectionService {
  constructor(
    private readonly store: SqliteStateStore,
    private readonly sink: MemoryProjectionSink,
    private readonly clock: () => Date = () => new Date(),
  ) {}

  async rebuild(taskId: string): Promise<ReadonlyMap<string, string>> {
    if (!this.store.getTask(taskId)) throw new Error(`Task not found: ${taskId}`);
    const memories = this.store.listMemoryEntries('task', taskId)
      .filter((memory) => memory.status === 'active' && (!memory.expiresAt || memory.expiresAt > this.clock().toISOString()))
      .sort(compareMemory);
    const files = projectionFiles(memories);
    await this.sink.replace(taskId, files);
    return files;
  }
}

function projectionFiles(memories: MemoryEntryRecord[]): ReadonlyMap<string, string> {
  const files = new Map<string, string>();
  const catalog = memories.map((memory) =>
    `- [${memory.id}](capsules/${safeFileName(memory.id)}.md) — ${safeProjectionText(memory.title)}: ${safeProjectionText(memory.description)}`);
  files.set('INDEX.md', heading('Task memory index', catalog.join('\n') || '_No active task memories._'));
  const latestCheckpoint = memories.filter((memory) => memory.kind === 'checkpoint').at(-1);
  files.set('CURRENT.md', heading('Current continuity checkpoint', latestCheckpoint
    ? safeProjectionText(latestCheckpoint.content)
    : '_No checkpoint is available._'));
  files.set('MEMORY.md', heading('Memory capsules', catalog.join('\n') || '_No active task memories._'));
  files.set('DECISIONS.md', grouped(memories, ['decision'], 'Confirmed decisions'));
  files.set('TODO.md', grouped(memories, ['todo'], 'Open task memory'));
  files.set('PROJECTS.md', grouped(memories, ['project'], 'Project memory'));
  const latestDream = memories.filter((memory) => memory.kind === 'episode' && memory.createdBy.startsWith('system:dream')).at(-1);
  files.set('LAST_DREAM.md', heading('Last Dream summary', latestDream
    ? safeProjectionText(latestDream.content)
    : '_No Dream summary is available._'));
  for (const memory of memories) {
    files.set(`capsules/${safeFileName(memory.id)}.md`, heading(
      safeProjectionText(memory.title),
      [
        `- Scope: task`, `- Kind: ${memory.kind}`, `- Version: ${memory.version}`,
        `- Tags: ${memory.tags.map(safeProjectionText).join(', ') || 'none'}`,
        '', safeProjectionText(memory.content),
      ].join('\n'),
    ));
  }
  return files;
}

function grouped(memories: MemoryEntryRecord[], kinds: MemoryEntryRecord['kind'][], title: string): string {
  const body = memories.filter((memory) => kinds.includes(memory.kind)).map((memory) =>
    `## ${safeProjectionText(memory.title)}\n\n${safeProjectionText(memory.content)}`).join('\n\n');
  return heading(title, body || '_None._');
}

function heading(title: string, body: string): string {
  return `<!-- Generated by link_bot; SQLite is authoritative. Edits are overwritten. -->\n# ${title}\n\n${body}\n`;
}

function safeProjectionText(value: string): string {
  const cleaned = value.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '');
  if (/(?:api[_-]?key|access[_-]?token|secret|password|private[_-]?key)\s*[:=]/i.test(cleaned)
    || /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/.test(cleaned)) {
    return '[redacted: possible secret]';
  }
  return cleaned;
}

function safeFileName(value: string): string {
  const safe = value.replace(/[^A-Za-z0-9._-]/g, '-').slice(0, 120);
  if (!safe) throw new Error('Memory id has no projection-safe characters.');
  return safe;
}

function compareMemory(left: MemoryEntryRecord, right: MemoryEntryRecord): number {
  return left.createdAt.localeCompare(right.createdAt) || left.id.localeCompare(right.id);
}
